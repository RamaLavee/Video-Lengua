def timeline():
    """Devuelve escenas con inicio y fin calculados (las transiciones encadenadas se solapan)."""
    out = []
    t = 0.0
    for i, s in enumerate(SCENES):
        kind, d = s['trans']
        if i > 0 and kind in ('fade', 'paper'):
            t -= d
        out.append(dict(s, start=round(t, 3), end=round(t + s['dur'], 3)))
        t += s['dur']
    return out


